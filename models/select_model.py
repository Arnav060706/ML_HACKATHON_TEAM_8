"""
Model selection from the recorded experiment results (no retraining).

Reads results/cv_per_fold.csv and results/model_comparison.csv written by
models/run_experiments.py and produces:

  results/model_selection.csv        one row per model with every selection criterion
  results/model_selection.md         ranked table + the decision and its justification
  results/confusion_matrices.png     student-test confusion matrices (threshold 0.5)

Selection protocol (decided before looking at the student-test numbers):
  1. Primary metric: mean GroupKFold CV Top-1 accuracy on reliable points
     (did the best-scoring candidate pick the reference arc?) -- this is the
     route-matching objective, measured on the 80 training trips only.
  2. Because the classifier's probabilities become the HMM emission scores,
     CV log loss (probability quality) is the second criterion.
  3. CV macro-F1 (mean +/- std over folds) for row-level quality and stability.
  4. The 10 student-test trips confirm generalisation (Top-1, macro-F1,
     log loss, route continuity); inference time and train-vs-CV gap
     (overfitting) are reported as tie-breakers.
Evaluator-test data is never used.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
NAMES = {"logreg": "Logistic Regression", "knn": "KNN (k=25)", "rf": "Random Forest",
         "hist_gradient_boosting": "HistGradientBoosting", "lightgbm": "LightGBM", "mlp": "MLP (64,32)"}


def main():
    folds = pd.read_csv(RES / "cv_per_fold.csv")
    comp = pd.read_csv(RES / "model_comparison.csv")
    folds = folds[~folds.model.str.startswith("baseline")]
    test = comp[comp.split == "student_test10"].set_index("model")

    g = folds.groupby("model")
    sel = pd.DataFrame({
        "cv_top1_reliable_mean": g.top1_reliable_points.mean(),
        "cv_top1_reliable_std": g.top1_reliable_points.std(),
        "cv_log_loss_mean": g.log_loss.mean(),
        "cv_macro_f1_mean": g.macro_f1.mean(),
        "cv_macro_f1_std": g.macro_f1.std(),
        "cv_route_continuity": g.route_continuity.mean(),
        "train_macro_f1": g.train_macro_f1.mean(),
    })
    sel["train_minus_cv_macro_f1"] = sel.train_macro_f1 - sel.cv_macro_f1_mean
    # per-fold wins
    for met, best in [("top1_reliable_points", "max"), ("macro_f1", "max"), ("log_loss", "min")]:
        idx = getattr(folds.groupby("fold")[met], f"idx{best}")()
        sel[f"folds_won_{met}"] = folds.loc[idx].model.value_counts().reindex(sel.index).fillna(0).astype(int)
    for c_out, c_in in [("test_top1_all", "top1_all_points"), ("test_top1_reliable", "top1_reliable_points"),
                        ("test_macro_f1", "macro_f1"), ("test_log_loss", "log_loss"),
                        ("test_route_continuity", "route_continuity"),
                        ("test_inference_s", "predict_time_s"), ("fit_time_s", "fit_time_s")]:
        sel[c_out] = test.loc[sel.index, c_in]

    # ranking: primary CV Top-1, then CV log loss, then CV macro-F1
    sel["rank_cv_top1"] = sel.cv_top1_reliable_mean.rank(ascending=False).astype(int)
    sel["rank_cv_log_loss"] = sel.cv_log_loss_mean.rank().astype(int)
    sel["rank_cv_macro_f1"] = sel.cv_macro_f1_mean.rank(ascending=False).astype(int)
    sel["mean_rank_cv"] = sel[["rank_cv_top1", "rank_cv_log_loss", "rank_cv_macro_f1"]].mean(axis=1)
    sel = sel.sort_values(["mean_rank_cv", "rank_cv_top1"])
    sel.insert(0, "model_name", [NAMES.get(m, m) for m in sel.index])
    sel.to_csv(RES / "model_selection.csv", index_label="model")
    best = sel.index[0]

    # ---- markdown --------------------------------------------------------------
    b = sel.loc[best]
    runner = sel.index[1]
    r = sel.loc[runner]
    top_test = sel.test_top1_all.idxmax()
    lines = ["# Model selection (generated by `models/select_model.py`)", "",
             "Partitions: CV = GroupKFold(5) by trip on the 80 **train** trips; test = the 10 "
             "**student_test** trips. Evaluator data is not used.", "",
             "| Model | CV Top-1 (reliable) | CV log loss | CV macro-F1 (mean ± std) | train − CV macro-F1 | "
             "folds won (Top-1 / F1 / log loss) | test Top-1 | test macro-F1 | test log loss | "
             "test continuity | inference (s, 135k rows) |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for m, x in sel.iterrows():
        lines.append(
            f"| {'**' + x.model_name + '**' if m == best else x.model_name} | {x.cv_top1_reliable_mean:.4f} ± "
            f"{x.cv_top1_reliable_std:.4f} | {x.cv_log_loss_mean:.4f} | {x.cv_macro_f1_mean:.4f} ± "
            f"{x.cv_macro_f1_std:.4f} | {x.train_minus_cv_macro_f1:+.4f} | "
            f"{x.folds_won_top1_reliable_points} / {x.folds_won_macro_f1} / {x.folds_won_log_loss} | "
            f"{x.test_top1_all:.4f} | {x.test_macro_f1:.4f} | {x.test_log_loss:.4f} | "
            f"{x.test_route_continuity:.4f} | {x.test_inference_s:.3f} |")
    lines += ["", f"## Decision: {b.model_name}", "",
              f"* **Primary (CV Top-1, reliable points):** {b.cv_top1_reliable_mean:.4f}, rank "
              f"{int(b.rank_cv_top1)} of {len(sel)}.",
              f"* **Probability quality (CV log loss):** {b.cv_log_loss_mean:.4f}, rank "
              f"{int(b.rank_cv_log_loss)}; best log loss in {b.folds_won_log_loss} of 5 folds. "
              "This matters because the probabilities are the HMM emission scores.",
              f"* **CV macro-F1:** {b.cv_macro_f1_mean:.4f} ± {b.cv_macro_f1_std:.4f}, rank "
              f"{int(b.rank_cv_macro_f1)}; best in {b.folds_won_macro_f1} of 5 folds.",
              f"* **Student-test confirmation:** Top-1 {b.test_top1_all:.4f}, macro-F1 {b.test_macro_f1:.4f}, "
              f"log loss {b.test_log_loss:.4f}, route continuity {b.test_route_continuity:.4f}."]
    if top_test != best:
        t = sel.loc[top_test]
        lines.append(f"* The highest student-test Top-1 is {t.model_name} ({t.test_top1_all:.4f}), "
                     f"{100 * (t.test_top1_all - b.test_top1_all):.2f} pp above {b.model_name}. That is "
                     f"about {round((t.test_top1_all - b.test_top1_all) * 19160)} of 19,160 points, which is "
                     "within noise, and it is worse on CV Top-1 and CV log loss.")
    lines += [f"* **Runner-up:** {r.model_name} (CV Top-1 {r.cv_top1_reliable_mean:.4f}, CV log loss "
              f"{r.cv_log_loss_mean:.4f}).",
              f"* **Over-fitting check:** train − CV macro-F1 = {b.train_minus_cv_macro_f1:+.4f}: a mild "
              "gap, expected for deep trees (max_depth=18). CV and student-test scores agree, so it "
              "generalises. Bayesian tuning (min_samples_leaf, max_depth, max_features) should target "
              "this gap.",
              f"* **Cost:** inference {b.test_inference_s:.3f} s for the 135,725 student-test candidate "
              f"rows (10 trips), well within an interactive API budget.",
              "* All models clearly beat the untrained rule baselines (student-test Top-1: nearest arc "
              "0.540, nearest arc with a heading filter 0.838).", ""]
    (RES / "model_selection.md").write_text("\n".join(lines), encoding="utf-8")

    # ---- confusion matrices (student-test, threshold 0.5) ------------------------
    models = list(sel.index)
    fig, axes = plt.subplots(1, len(models), figsize=(3.3 * len(models), 3.4))
    for ax, m in zip(axes, models):
        row = test.loc[m]
        cm = np.array([[row.tn, row.fp], [row.fn, row.tp]], dtype=float)
        norm = cm / cm.sum(axis=1, keepdims=True)
        ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        for i in range(2):
            for j in range(2):
                ax.text(j, i, f"{int(cm[i, j]):,}\n({norm[i, j]:.1%})", ha="center", va="center",
                        color="white" if norm[i, j] > 0.5 else "black", fontsize=9)
        ax.set_xticks([0, 1], ["pred 0", "pred 1"])
        ax.set_yticks([0, 1], ["true 0", "true 1"])
        ax.set_title(NAMES.get(m, m) + (" (selected)" if m == best else ""), fontsize=10)
    fig.suptitle("Student-test confusion matrices (reliable candidate rows, threshold 0.5; "
                 "row-normalised % in brackets)")
    plt.tight_layout()
    plt.savefig(RES / "confusion_matrices.png", dpi=150)
    print(f"Selected: {b.model_name}. Wrote results/model_selection.csv, results/model_selection.md, "
          "results/confusion_matrices.png")


if __name__ == "__main__":
    main()
